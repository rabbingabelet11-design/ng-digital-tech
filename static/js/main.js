function changeLanguage(language) {
    if (!translations[language]) {
        language = "fr";
    }

    localStorage.setItem("ngdt-language", language);
    document.documentElement.lang = language;

    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.getAttribute("data-i18n");
        const translatedText = translations[language][key];

        if (translatedText !== undefined) {
            element.textContent = translatedText;
        }
    });

    document.querySelectorAll("[data-i18n-attr]").forEach(element => {
        const instructions = element.getAttribute("data-i18n-attr");

        instructions.split(";").forEach(instruction => {
            const separator = instruction.indexOf(":");

            if (separator === -1) return;

            const attribute = instruction.slice(0, separator).trim();
            const key = instruction.slice(separator + 1).trim();
            const translatedText = translations[language][key];

            if (translatedText !== undefined) {
                element.setAttribute(attribute, translatedText);
            }
        });
    });

    document.querySelectorAll("[data-lang], [data-language]").forEach(button => {
        const buttonLanguage =
            button.getAttribute("data-lang") ||
            button.getAttribute("data-language");

        const selected = buttonLanguage === language;

        button.classList.toggle("active", selected);
        button.setAttribute("aria-pressed", selected ? "true" : "false");
    });
}

document.addEventListener("DOMContentLoaded", () => {
    const savedLanguage = localStorage.getItem("ngdt-language") || "fr";

    changeLanguage(savedLanguage);

    document.querySelectorAll("[data-lang], [data-language]").forEach(button => {
        button.addEventListener("click", () => {
            const language =
                button.getAttribute("data-lang") ||
                button.getAttribute("data-language");

            changeLanguage(language);
        });
    });
});

window.changeLanguage = changeLanguage;
